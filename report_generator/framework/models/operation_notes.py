def build_default_sheet_notes(detection_data, default_notes):
    """把按基础项目名组织的说明展开成 {sheet_key: 说明文本}。"""
    out = {}
    for items in detection_data.values():
        for item_name, components in items.items():
            note = default_notes.get(item_name, "")
            if not note:
                for key in default_notes:
                    if item_name.startswith(key):
                        note = default_notes[key]
                        break
            if components:
                for component in components:
                    out[f"{item_name}（{component}）"] = note
            else:
                out[item_name] = note
    return out
